/**
 * Phase 74 — Part D detector catalogue (D5–D13).
 * Aligns with web/lib/detectors.ts roles/meanings and KNOWN_LIMITATIONS.md.
 */

function detectorChapter(parts: {
  role: string;
  meaning: string;
  measures: string;
  flags: string;
  knobs: string[];
  catches: string[];
  misses: string[];
  ui: string;
  seeAlso: string;
}): string {
  return [
    `## Role`,
    "",
    `**${parts.role}** — ${parts.meaning}`,
    "",
    "## What it measures",
    "",
    parts.measures,
    "",
    "## How it flags",
    "",
    parts.flags,
    "",
    "## Key knobs (YAML)",
    "",
    ...parts.knobs.map((k) => `- ${k}`),
    "",
    "## Catches",
    "",
    ...parts.catches.map((c) => `- ${c}`),
    "",
    "## Misses / over-flags",
    "",
    ...parts.misses.map((m) => `- ${m}`),
    "",
    "## UI surfaces",
    "",
    parts.ui,
    "",
    "## See also",
    "",
    parts.seeAlso,
  ].join("\n");
}

