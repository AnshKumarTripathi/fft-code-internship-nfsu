"""Compare IsolationForest vs autoencoder on the demo eval label set (Phase 53).

Runs detect-ml twice (IF then AE) against a shared warehouse after upstream
stages, evaluates each against labels, and writes a comparison table under
``data/reports/eval/``.

Does **not** change the default ``ml.model_type`` (stays isolation_forest).

Example::

    python scripts/compare_ml_models.py \\
        --config config/pipeline.yaml \\
        --labels tests/fixtures/labels/demo_eval.csv
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

CODE_ROOT = Path(__file__).resolve().parents[1]
if str(CODE_ROOT) not in sys.path:
    sys.path.insert(0, str(CODE_ROOT))

from src.config import load_config  # noqa: E402
from src.detectors.ml.persist import run_detect_ml  # noqa: E402
from src.evaluation.persist import run_evaluate  # noqa: E402


def _run_ml_and_eval(
    config: dict[str, Any],
    *,
    model_type: str,
    labels_path: str,
    output_dir: Path,
    config_path: str,
) -> dict[str, Any]:
    config = dict(config)
    config["ml"] = dict(config.get("ml") or {})
    config["ml"]["model_type"] = model_type
    config["ml"]["mode"] = "refit_and_snapshot"
    config["ml"]["snapshot_id"] = None
    if model_type == "autoencoder":
        config["ml"].setdefault("ae_hidden_dims", [32, 8, 32])
        config["ml"].setdefault("ae_max_iter", 200)

    summary = run_detect_ml(config, config_path=config_path)
    model_out = output_dir / model_type
    model_out.mkdir(parents=True, exist_ok=True)
    config["evaluation"] = dict(config.get("evaluation") or {})
    config["evaluation"]["labels_path"] = labels_path
    config["evaluation"]["output_dir"] = str(model_out)
    eval_summary = run_evaluate(config, config_path=config_path)
    metrics_path = Path(eval_summary.metrics_json_path)
    metrics = json.loads(metrics_path.read_text(encoding="utf-8"))
    return {
        "model_type": model_type,
        "detect_summary": summary.as_dict(),
        "metrics": metrics,
        "metrics_json_path": str(metrics_path),
    }


def _ml_metrics(payload: dict[str, Any]) -> dict[str, Any]:
    detectors = payload.get("detectors") or {}
    if isinstance(detectors, dict) and isinstance(detectors.get("ml"), dict):
        return detectors["ml"]
    return {}


def _markdown_table(rows: list[dict[str, Any]]) -> str:
    lines = [
        "# ML model comparison (Phase 53)",
        "",
        "Default YAML remains `isolation_forest`. Opt into `autoencoder` or "
        "`onnx` only after reviewing these metrics.",
        "",
        "| model_type | windows_flagged | precision | recall | f1 |",
        "|---|---:|---:|---:|---:|",
    ]
    for row in rows:
        ml = _ml_metrics(row.get("metrics") or {})
        summary = row.get("detect_summary") or {}
        lines.append(
            "| {model} | {flagged} | {p} | {r} | {f1} |".format(
                model=row.get("model_type"),
                flagged=summary.get("windows_flagged", ""),
                p=_fmt(ml.get("precision")),
                r=_fmt(ml.get("recall")),
                f1=_fmt(ml.get("f1")),
            )
        )
    lines.append("")
    lines.append(
        "Generated by `scripts/compare_ml_models.py`. Do not flip the default "
        "without evidence on a representative label set."
    )
    lines.append("")
    return "\n".join(lines)


def _fmt(value: Any) -> str:
    try:
        return f"{float(value):.3f}"
    except (TypeError, ValueError):
        return "n/a"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="config/pipeline.yaml")
    parser.add_argument(
        "--labels",
        default="tests/fixtures/labels/demo_eval.csv",
    )
    parser.add_argument(
        "--output-dir",
        default="data/reports/eval",
        help="Directory for ml_model_compare.md / .json",
    )
    parser.add_argument(
        "--skip-detect",
        action="store_true",
        help="Only rebuild the table from existing per-model evaluate outputs",
    )
    args = parser.parse_args(argv)

    config_path = str(Path(args.config))
    config = load_config(config_path)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    results: list[dict[str, Any]] = []
    if args.skip_detect:
        for model_type in ("isolation_forest", "autoencoder"):
            metrics_path = output_dir / model_type / "metrics.json"
            if not metrics_path.is_file():
                print(f"missing {metrics_path}; run without --skip-detect", file=sys.stderr)
                return 1
            results.append(
                {
                    "model_type": model_type,
                    "detect_summary": {},
                    "metrics": json.loads(metrics_path.read_text(encoding="utf-8")),
                }
            )
    else:
        for model_type in ("isolation_forest", "autoencoder"):
            print(f"=== detect-ml + evaluate ({model_type}) ===")
            results.append(
                _run_ml_and_eval(
                    config,
                    model_type=model_type,
                    labels_path=str(Path(args.labels)),
                    output_dir=output_dir,
                    config_path=config_path,
                )
            )

    compare_json = output_dir / "ml_model_compare.json"
    compare_md = output_dir / "ml_model_compare.md"
    compare_json.write_text(json.dumps(results, indent=2, default=str), encoding="utf-8")
    compare_md.write_text(_markdown_table(results), encoding="utf-8")
    print(f"Wrote {compare_md}")
    print(f"Wrote {compare_json}")
    print("Default remains isolation_forest (see config/pipeline.yaml).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
